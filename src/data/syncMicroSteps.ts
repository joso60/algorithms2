import type { ProcessState, SlideTraceStep } from './syncData';

/**
 * Micro-step traces: ONE instruction (or one atomic primitive call) per step.
 * Variables and process states are merged cumulatively by the engine, so each
 * step only lists what actually changed.
 */

type Vars = Record<string, string | number | boolean>;

interface Micro {
  /** Process executing this single instruction */
  p: string;
  /** Text shown in the "executed instruction" chip */
  line: string;
  /** Unique reference to the highlighted line in the code panel */
  ref: string;
  /** Process states that changed */
  states?: Record<string, ProcessState>;
  /** Shared variables that changed */
  vars?: Vars;
  /** CPU registers that changed */
  regs?: Record<string, number | string>;
  /** Explicit waiting queue (omit to derive from BLOCKED/WAITING states) */
  q?: string[];
  math?: string;
  text: string;
  milestone?: string;
  spin?: string[];
  violation?: string;
}

const build = (list: Micro[]): SlideTraceStep[] =>
  list.map((m, i) => ({
    stepIndex: i + 1,
    activeProcess: m.p,
    codeLine: m.line,
    lineRef: m.ref,
    processStates: m.states ?? {},
    sharedVariables: m.vars ?? {},
    registers: m.regs,
    waitingQueue: m.q,
    mathEval: m.math,
    slideMilestone: m.milestone,
    spinningProcesses: m.spin,
    isViolation: Boolean(m.violation),
    violationMessage: m.violation,
    explanation: m.text,
  }));

